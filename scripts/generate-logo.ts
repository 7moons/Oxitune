// Writes src-tauri/icons/logo.svg: an oscillating ring with a play button,
// drawn as a dot matrix (an LED panel). Each dot is sized by how much of the
// mark covers its cell and colored along a neon red ramp running from the
// top-left to the bottom-right. Run `bun scripts/generate-icons.ts`
// afterwards to render the icon files.
import fs from 'fs';
import path from 'path';

const SIZE = 130;
const N = 34;
const CELL = SIZE / N;
const MAX_R = 1.25;
const UNLIT_R = 0.4;
const SAMPLES = 8;

type Pt = [number, number];
type Rgb = [number, number, number];

function inTriangle(x: number, y: number, a: Pt, b: Pt, c: Pt): boolean {
  const s = (p: Pt, q: Pt) => (x - q[0]) * (p[1] - q[1]) - (p[0] - q[0]) * (y - q[1]);
  const d1 = s(a, b);
  const d2 = s(b, c);
  const d3 = s(c, a);
  return !((d1 < 0 || d2 < 0 || d3 < 0) && (d1 > 0 || d2 > 0 || d3 > 0));
}

function inMark(x: number, y: number): boolean {
  const r = 38 + 3.5 * Math.sin(6 * Math.atan2(y - 65, x - 65));
  if (Math.abs(Math.hypot(x - 65, y - 65) - r) <= 4.2) return true;
  return inTriangle(x, y, [57, 51], [57, 79], [81, 65]);
}

function coverage(cx: number, cy: number): number {
  let hit = 0;
  for (let i = 0; i < SAMPLES; i++) {
    for (let j = 0; j < SAMPLES; j++) {
      const x = cx - CELL / 2 + (i + 0.5) * (CELL / SAMPLES);
      const y = cy - CELL / 2 + (j + 0.5) * (CELL / SAMPLES);
      if (inMark(x, y)) hit++;
    }
  }
  return hit / (SAMPLES * SAMPLES);
}

const STOPS: [number, Rgb][] = [
  [0, [230, 20, 35]],
  [0.6, [255, 45, 55]],
  [1, [255, 120, 110]],
];

function glow(t: number): string {
  const k = Math.max(0, Math.min(1, t));
  let c: Rgb = STOPS[STOPS.length - 1][1];
  for (let i = 1; i < STOPS.length; i++) {
    const [t1, c1] = STOPS[i];
    const [t0, c0] = STOPS[i - 1];
    if (k <= t1) {
      const f = (k - t0) / (t1 - t0);
      c = c0.map((v, n) => v + (c1[n] - v) * f) as Rgb;
      break;
    }
  }
  return `#${c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')}`;
}

// Unlit dots only where they sit well inside the rounded tile.
function insideTile(x: number, y: number): boolean {
  const r = 30;
  const m = 6;
  const qx = Math.max(Math.abs(x - 65) - (65 - r), 0);
  const qy = Math.max(Math.abs(y - 65) - (65 - r), 0);
  return Math.hypot(qx, qy) <= r - m;
}

const lit: string[] = [];
const unlit: string[] = [];
for (let i = 0; i < N; i++) {
  for (let j = 0; j < N; j++) {
    const cx = i * CELL + CELL / 2;
    const cy = j * CELL + CELL / 2;
    const cov = coverage(cx, cy);
    if (cov > 0.15) {
      const r = UNLIT_R + (MAX_R - UNLIT_R) * Math.sqrt(cov);
      const t = (cx - 25 + (cy - 25)) / 160;
      lit.push(`<circle cx="${cx.toFixed(2)}" cy="${cy.toFixed(2)}" r="${r.toFixed(2)}" fill="${glow(t)}"/>`);
    } else if (insideTile(cx, cy)) {
      unlit.push(`<circle cx="${cx.toFixed(2)}" cy="${cy.toFixed(2)}" r="${UNLIT_R}"/>`);
    }
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 ${SIZE} ${SIZE}">
  <!-- Generated by scripts/generate-logo.ts -->
  <defs>
    <filter id="bloom" x="-10%" y="-10%" width="120%" height="120%">
      <feGaussianBlur stdDeviation="1.6" result="b"/>
      <feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
  </defs>
  <rect width="${SIZE}" height="${SIZE}" rx="30" fill="#07070a"/>
  <g fill="#1c1c22">
    ${unlit.join('\n    ')}
  </g>
  <g filter="url(#bloom)">
    ${lit.join('\n    ')}
  </g>
</svg>
`;

fs.writeFileSync(path.resolve('src-tauri/icons/logo.svg'), svg);
console.log(`logo.svg: ${lit.length} lit dots, ${unlit.length} unlit.`);
